// Геометрия SVG (поле 4×4)
const SVG = {
  size: 640,          // сторона SVG
  padding: 80,        // отступ от края
  get cell() { return (this.size - 2 * this.padding) / 3; }, // шаг между центрами
};

// Центр ячейки по её id -> координаты SVG (x, y)
function cellCenter(id) {
  const { row, col } = cellIdToRC(id);
  return {
    x: SVG.padding + col * SVG.cell,
    y: SVG.padding + row * SVG.cell,
  };
}

