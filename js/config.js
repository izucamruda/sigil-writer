// Нумерация ячеек 1..16 слева направо, сверху вниз (раздел 1.3)
// cellId -> {row, col} (0-based для удобства кода)
function cellIdToRC(id) {
  if (id < 1 || id > 16) throw new Error('cellId out of range: ' + id);
  const i = id - 1;
  return { row: Math.floor(i / 4), col: i % 4 };
}

